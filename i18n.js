  const storageKey = 'pondo.language';
  let language = 'uk';
  function storedLanguage() {
    try { const saved = localStorage.getItem(storageKey); return ['uk', 'ru', 'en'].includes(saved) ? saved : 'uk'; }
    catch { return 'uk'; }
  }
  language = storedLanguage();
  function t(key, params = {}, locale = language) {
    const value = messages[locale][key] ?? messages.uk[key] ?? key;
    return value.replace(/\{(\w+)\}/g, (match, name) => String(params[name] ?? match));
  }
  function apply(root = document) {
    root.querySelectorAll('[data-i18n]').forEach(node => { node.textContent = t(node.dataset.i18n); });
    // Only our trusted dictionary contains markup; no user input is passed to innerHTML.
    root.querySelectorAll('[data-i18n-html]').forEach(node => { node.innerHTML = t(node.dataset.i18nHtml); });
    for (const attribute of ['aria-label', 'aria-roledescription', 'alt', 'placeholder', 'content']) {
      root.querySelectorAll(`[data-i18n-${attribute}]`).forEach(node => node.setAttribute(attribute, t(node.getAttribute(`data-i18n-${attribute}`))));
    }
    document.documentElement.lang = language;
    document.querySelectorAll('[data-language]').forEach(button => button.setAttribute('aria-pressed', String(button.dataset.language === language)));
    document.querySelector('.about-mark')?.setAttribute('data-mark-label', t('hero.mark'));
  }
  function setLanguage(next, save = true) {
    if (!['uk', 'ru', 'en'].includes(next)) return;
    language = next;
    if (save) { try { localStorage.setItem(storageKey, next); } catch { /* Keep the current choice for this page only. */ } }
    apply();
    window.dispatchEvent(new CustomEvent('languagechange', { detail: { language } }));
  }
  window.PondoI18n = Object.freeze({
    t, apply, setLanguage, storageKey,
    get language() { return language; },
    product(product, field = 'name', locale = language) { return t(`products.${product.id}.${field}`, {}, locale); },
    count(value) { const plural = new Intl.PluralRules(language).select(value); return t(`catalog.count.${plural === 'one' ? 'one' : plural === 'few' ? 'few' : 'many'}`, { count: value }); }
  });
  document.addEventListener('click', event => {
    const button = event.target.closest('[data-language]');
    if (button) setLanguage(button.dataset.language);
  });
  window.addEventListener('storage', event => { if (event.key === storageKey || event.key === null) setLanguage(storedLanguage(), false); });
  window.addEventListener('pageshow', event => { if (event.persisted) setLanguage(storedLanguage(), false); });
  apply();
